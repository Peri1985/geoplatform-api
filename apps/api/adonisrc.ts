import { indexEntities } from '@adonisjs/core/generators'
import { defineConfig } from '@adonisjs/core/app'
import { generateRegistry } from '@tuyau/core/hooks'
import { spawn } from 'node:child_process'

export default defineConfig({
  /*
  |--------------------------------------------------------------------------
  | Experimental flags
  |--------------------------------------------------------------------------
  |
  | The following features will be enabled by default in the next major release
  | of AdonisJS. You can opt into them today to avoid any breaking changes
  | during upgrade.
  |
  */
  experimental: {},

  /*
  |--------------------------------------------------------------------------
  | Commands
  |--------------------------------------------------------------------------
  |
  | List of ace commands to register from packages. The application commands
  | will be scanned automatically from the "./commands" directory.
  |
  */
  commands: [() => import('@adonisjs/core/commands'), () => import('@adonisjs/lucid/commands')],

  /*
  |--------------------------------------------------------------------------
  | Service providers
  |--------------------------------------------------------------------------
  |
  | List of service providers to import and register when booting the
  | application
  |
  */
  providers: [
    () => import('@adonisjs/core/providers/app_provider'),
    () => import('@adonisjs/core/providers/hash_provider'),
    {
      file: () => import('@adonisjs/core/providers/repl_provider'),
      environment: ['repl', 'test'],
    },
    () => import('@adonisjs/core/providers/vinejs_provider'),
    () => import('@adonisjs/redis/redis_provider'),
    () => import('@adonisjs/limiter/limiter_provider'),
    () => import('@adonisjs/shield/shield_provider'),
    () => import('@adonisjs/lucid/database_provider'),
    () => import('@adonisjs/cors/cors_provider'),
    () => import('@adonisjs/auth/auth_provider'),
    () => import('#providers/api_provider'),
    () => import('@adonisjs/drive/drive_provider'),
  ],

  /*
  |--------------------------------------------------------------------------
  | Preloads
  |--------------------------------------------------------------------------
  |
  | List of modules to import before starting the application.
  |
  */
  preloads: [
    () => import('#start/routes'),
    () => import('#start/kernel'),
    () => import('#start/validator'),
    {
      file: () => import('#start/audit'),
      environment: ['web'],
    },
  ],

  /*
  |--------------------------------------------------------------------------
  | Tests
  |--------------------------------------------------------------------------
  |
  | List of test suites to organize tests by their type. Feel free to remove
  | and add additional suites.
  |
  */
  tests: {
    suites: [
      {
        files: ['tests/unit/**/*.spec.{ts,js}'],
        name: 'unit',
        timeout: 2000,
      },
      {
        files: ['tests/functional/**/*.spec.{ts,js}'],
        name: 'functional',
        timeout: 30000,
      },
    ],
    forceExit: false,
  },

  /*
  |--------------------------------------------------------------------------
  | Metafiles
  |--------------------------------------------------------------------------
  |
  | A collection of files you want to copy to the build folder when creating
  | the production build.
  |
  */
  metaFiles: [
    // Generated by `node ace docs:generate`, served by GET /docs.json
    { pattern: '.adonisjs/openapi.json', reloadServer: false },
  ],

  hooks: {
    init: [
      indexEntities({
        transformers: { enabled: true },
      }),
      generateRegistry(),
      /**
       * The OpenAPI document (GET /docs) out of the registry Tuyau just wrote.
       * Added after generateRegistry, so it runs once the registry is on disk.
       * In the background: it type-checks the whole app and takes a few seconds.
       */
      {
        run(_, hooks) {
          hooks.add('routesScanned', (parent) => {
            const child = spawn(process.execPath, ['ace', 'docs:generate'], { stdio: 'ignore' })
            child.on('exit', (code) => {
              if (code === 0) parent.ui.logger.info('openapi: created .adonisjs/openapi.json')
              else parent.ui.logger.warning('openapi: "node ace docs:generate" failed')
            })
          })
        },
      },
      /**
       * Our own barrel file: every app/filters/*_filter.ts in #generated/filters,
       * e.g. filters.Organization for organization_filter.ts
       */
      {
        run(_, __, indexGenerator) {
          indexGenerator.add('filters', {
            source: 'app/filters',
            glob: ['**/*_filter.ts'],
            as: 'barrelFile',
            exportName: 'filters',
            importAlias: '#filters',
            removeSuffix: 'filter',
            // Models use them right away, not lazily like controllers
            disableLazyImports: true,
            output: '.adonisjs/server/filters.ts',
            comment: true,
          })
        },
      },
    ],
  },
})
